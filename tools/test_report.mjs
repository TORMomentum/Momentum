#!/usr/bin/env node
// Turns one Vitest JSON run into docs/test-report.md: every test, grouped by
// SRS feature, with the function it exercises and its result. Generated, so it
// never drifts from the suite — regenerate, never hand-edit.
//
//   npm run test:report                        runs the suite, then writes the report
//   node tools/test_report.mjs <vitest.json>   reports an existing JSON run
//
// A failing suite still produces a report — the failures are what it is for.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

// First match wins. Each feature's requirement IDs are SRS §7 (Traceability).
const features = [
  ["F1 TOR intake", "FR-A-1…3 · NFR-S1, S3, S5", /modules\/intake\/|lib\/(safe-fetch|file-type|hash|storage-key)|adapters\/(gcs\.storage|mongo\.queue)|workers\/reconcile|src\/app\.test/],
  ["F2 Thai reading", "FR-B-1, B-2, B-4 · NFR-F3, F6", /modules\/extraction\/|adapters\/vertex|lib\/(pdf-text|parse-budget)|workers\/extract/],
  ["F3 Confidence and review", "FR-B-3, FR-G-1, G-2", /modules\/admin\/admin\.(routes|repository)|lib\/tor-state|AdminReviewView|RecordPanel/],
  ["F4 Search and detail", "FR-E-3…5 · NFR-F2, F7", /modules\/tors\/tors\.(routes|search)|lib\/(stream-document|byte-range|content-disposition)|SearchView|TorRecordView|search\.params/],
  ["F5 Matching and email", "FR-C-1…4 · NFR-F1", /modules\/(matching|notifications|match-quality)\/|mailer|MatchedTorsPanel|MatchLabelSheet/],
  ["F6 Profiles and accounts", "FR-D-1…3 · NFR-S1, S2", /modules\/(accounts|profile|bookmarks)\/|admin-accounts|auth-middleware|db\.accounts|VendorProfileView|features\/profile\/MatchingExtras|AdminVendorView/],
  ["F7 Dashboard and anomaly rule", "FR-E-1, E-2, E-6 · NFR-F4, F5", /modules\/stats\/|db\.stats|budget-year|backfill_cohorts|DashboardView|dashboard-filters/],
  ["F8 Quality checklist", "FR-F-1…4 · NFR-F5, F6", /checklist|ChecklistPanel/],
  ["F9 Taxonomy", "FR-G-3, FR-B-4", /packages\/seeds\/|TaxonomyPicker/],
  ["F10 PII and takedown", "FR-B-5, B-6 · NFR-S2, S3", /lib\/redact/],
  ["F12 Automated collection", "FR-A-4", /src\/sources\/|routes\/sources/],
  ["Cross-cutting: config, admin screens, shared UI, tooling", "NFR-S7", /./],
];

const out = "docs/test-report.md";
let input = process.argv[2];
if (!input) {
  input = join(tmpdir(), `tor-radar-vitest-${process.pid}.json`);
  try {
    execFileSync("npx", ["vitest", "run", "--reporter=json", `--outputFile=${input}`], { stdio: "ignore", shell: true });
  } catch {
    // Non-zero exit means a test failed; the JSON is still written.
  }
}

const run = JSON.parse(readFileSync(input, "utf8"));
const commit = execFileSync("git", ["rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
const result = { passed: "✅ Pass", failed: "❌ Fail", pending: "⏭ Skipped", skipped: "⏭ Skipped", todo: "⏭ Todo" };
const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\s+/g, " ");

const groups = features.map(([name, reqs]) => ({ name, reqs, files: [] }));
for (const file of run.testResults) {
  const path = file.name.split(/[\\/]/).join("/").replace(/^.*?\/(apps|packages|tools)\//, "$1/");
  const group = groups[features.findIndex(([, , pattern]) => pattern.test(path))];
  group.files.push({ path, tests: file.assertionResults });
}

const count = (tests, status) => tests.filter((t) => t.status === status).length;
const all = groups.flatMap((g) => g.files.flatMap((f) => f.tests));
const skipped = all.length - count(all, "passed") - count(all, "failed");

const lines = [
  "# Test report — TOR Radar",
  "",
  `_Generated by \`tools/test_report.mjs\` from one run of the full suite. Commit \`${commit}\`, ` +
    `${new Date(run.startTime).toISOString().slice(0, 16).replace("T", " ")} UTC. Do not edit by hand: run \`npm run test:report\`._`,
  "",
  `**${all.length} tests · ${count(all, "passed")} passed · ${count(all, "failed")} failed · ${skipped} skipped.** ` +
    "Skipped tests are the opt-in ones that call a paid or real external service (see [TESTING.md](TESTING.md) §1).",
  "",
  "Each row is one test: the function or route it exercises, the behaviour it asserts (input and expected outcome, in the test's own words), and the result. " +
    "Key cases with their concrete inputs are written out in [TESTING.md](TESTING.md) §2.",
  "",
  "| Feature | Requirements | Tests | Pass | Fail | Skipped |",
  "| :---- | :---- | ----: | ----: | ----: | ----: |",
  ...groups.map((g) => {
    const tests = g.files.flatMap((f) => f.tests);
    return `| ${g.name} | ${g.reqs} | ${tests.length} | ${count(tests, "passed")} | ${count(tests, "failed")} | ${tests.length - count(tests, "passed") - count(tests, "failed")} |`;
  }),
  "",
];

for (const g of groups) {
  if (g.files.length === 0) continue;
  lines.push(`## ${g.name}`, "", `Requirements: ${g.reqs}`, "");
  for (const f of g.files.sort((a, b) => a.path.localeCompare(b.path))) {
    const failed = count(f.tests, "failed");
    lines.push(
      `<details${failed ? " open" : ""}><summary><code>${f.path}</code> — ${count(f.tests, "passed")}/${f.tests.length} pass${failed ? `, <b>${failed} fail</b>` : ""}</summary>`,
      "",
      "| # | Function / route | Behaviour (input → expected) | Result |",
      "| ---: | :---- | :---- | :---- |",
      ...f.tests.map((t, i) => `| ${i + 1} | ${cell(t.ancestorTitles.at(-1) ?? "—")} | ${cell(t.title)} | ${result[t.status] ?? t.status} |`),
      "",
      "</details>",
      "",
    );
  }
}

writeFileSync(out, lines.join("\n"));
console.log(`${out}: ${all.length} tests, ${count(all, "failed")} failed.`);

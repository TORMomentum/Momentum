describe("normalizeCategory", () => {
  it("keeps a specific category already on the list", () => {
    for (const category of TOR_CATEGORIES) {
      if (category === "จ้างเหมาบริการ" || category === "ซื้อวัสดุและครุภัณฑ์อื่น ๆ" || category === "งานก่อสร้าง-อื่น ๆ") continue;
      expect(normalizeCategory(category, "ประกวดราคาซื้อรถบรรทุก")).toBe(category);
    }
  });

  it.each(cases)("files %s / %s as %s", (category, title, expected) => {
    expect(normalizeCategory(category, title)).toBe(expected);
  });

  it("does not read the e-bidding method as electronics", () => {
    expect(normalizeCategory("ซื้อครุภัณฑ์", "ประกวดราคาซื้อถุงพลาสติก ด้วยวิธีประกวดราคาอิเล็กทรอนิกส์ (e-bidding)")).toBe("ซื้อวัสดุและครุภัณฑ์อื่น ๆ");
  });

  it("returns null when nothing says which category, rather than guessing", () => {
    expect(normalizeCategory("", "")).toBeNull();
    expect(normalizeCategory(null)).toBeNull();
    expect(normalizeCategory("โครงการพัฒนาชุมชน")).toBeNull();
    expect(isTorCategory("ซื้อยา")).toBe(false);
  });
});
